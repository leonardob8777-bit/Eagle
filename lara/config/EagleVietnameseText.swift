/// Vietnamese for Eagle's interface: every `text(en:es:)` string, keyed by its English text, as in
/// `EagleChineseText`. Strings built with values (counts, names) are matched as templates. Anything
/// not listed stays in English. Interface text only.
enum EagleVietnameseText {
    static func translate(_ english: String) -> String {
        if let exact = table[english] { return exact }
        lock.lock(); defer { lock.unlock() }
        if let cached = cache[english] { return cached }
        var result = english
        for template in matchingTemplates {
            if let values = EagleChineseText.match(english, fragments: template.english) {
                var text = template.vietnamese
                for (index, value) in values.enumerated() {
                    text = text.replacingOccurrences(of: "{\(index)}", with: value)
                }
                result = text
                break
            }
        }
        if cache.count > 400 { cache.removeAll() }
        cache[english] = result
        return result
    }

    private static let lock = NSLock()
    nonisolated(unsafe) private static var cache: [String: String] = [:]

    private struct Template { let english: [String]; let vietnamese: String }

