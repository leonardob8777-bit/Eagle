import Foundation

/// Simplified Chinese for Eagle's interface: every `text(en:es:)` string, keyed by its English
/// text. Strings built with values (counts, names) are matched as templates. Anything not listed
/// stays in English. Interface text only.
enum EagleChineseText {
    static func translate(_ english: String) -> String {
        if let exact = table[english] { return exact }
        lock.lock(); defer { lock.unlock() }
        if let cached = cache[english] { return cached }
        var result = english
        for template in templates {
            if let values = match(english, fragments: template.english) {
                var text = template.chinese
                for (index, value) in values.enumerated() {
                    text = text.replacingOccurrences(of: "{\(index)}", with: value)
                }
                result = text
                break
            }
        }
        if cache.count > 400 { cache.removeAll() }
        cache[english] = result
        return result
    }

    private static let lock = NSLock()
    nonisolated(unsafe) private static var cache: [String: String] = [:]

    /// The values in `text` between the template's fixed fragments, or nil if it does not match.
    private static func match(_ text: String, fragments: [String]) -> [String]? {
        guard let first = fragments.first, text.hasPrefix(first) else { return nil }
        var rest = Substring(text.dropFirst(first.count))
        var values: [String] = []
        for index in 1..<fragments.count {
            let fragment = fragments[index]
            if index == fragments.count - 1 {
                guard rest.hasSuffix(fragment), rest.count >= fragment.count else { return nil }
                let value = rest.dropLast(fragment.count)
                guard !value.isEmpty else { return nil }
                values.append(String(value))
            } else {
                guard !fragment.isEmpty, let range = rest.range(of: fragment), range.lowerBound > rest.startIndex else { return nil }
                values.append(String(rest[rest.startIndex..<range.lowerBound]))
                rest = rest[range.upperBound...]
            }
        }
        return values
    }

